"""Fake AI providers for testing.

IMPORTANT: These classes MUST only be imported from test files.
They must never appear in production dependency wiring.

The fake providers return configurable responses so tests can exercise
every branch of the orchestrator without a running Ollama server.
"""

import json

from app.ai.base import (
    QuestGenerationRequest,
    RawModelOutput,
    ReflectionRequest,
    TextModelProvider,
)
from app.ai.prompts.quest_prompt import QUEST_PROMPT_VERSION


def _valid_quest_json(
    duration_minutes: int = 20,
    difficulty: str = "chill",
    xp_reward: int = 75,
) -> str:
    """Return a minimal valid quest JSON string."""
    return json.dumps(
        {
            "title": "The Fake Quest",
            "brief": "This is a fake quest generated by the test provider for testing purposes only.",
            "duration_minutes": duration_minutes,
            "difficulty": difficulty,
            "objectives": [
                {"id": "obj-1", "instruction": "Find a leaf on the ground", "optional": False},
                {
                    "id": "obj-2",
                    "instruction": "Photograph the most interesting thing nearby",
                    "optional": True,
                },
            ],
            "xp_reward": xp_reward,
            "evidence_required": True,
            "safety_notes": "Stay on public paths.",
        }
    )


class FakeTextProvider(TextModelProvider):
    """Configurable fake text provider for tests.

    Usage:
        provider = FakeTextProvider()                             # always succeeds
        provider = FakeTextProvider(fail_times=1)                # fail once then succeed
        provider = FakeTextProvider(response="bad json")         # always returns bad JSON
        provider = FakeTextProvider(response=None)               # always returns empty string
        provider = FakeTextProvider(reflection_text="...")       # custom reflection output
        provider = FakeTextProvider(reflection_fail=True)        # reflection raises error
    """

    def __init__(
        self,
        response: str | None = "AUTO",
        fail_times: int = 0,
        duration_minutes: int = 20,
        difficulty: str = "chill",
        xp_reward: int = 75,
        reflection_text: str | None = None,
        reflection_fail: bool = False,
    ) -> None:
        """
        Args:
            response:         Raw string for quest generation.  "AUTO" generates valid JSON.
                              None returns an empty string (triggers JSONParseError).
            fail_times:       Return empty string this many times before succeeding.
            duration_minutes: Duration to embed in the auto-generated JSON.
            difficulty:       Difficulty to embed in the auto-generated JSON.
            xp_reward:        XP reward to embed in the auto-generated JSON.
            reflection_text:  Custom plain-text reflection to return.  None uses default.
            reflection_fail:  If True, generate_reflection raises ProviderUnavailableError.
        """
        self._response = response
        self._fail_times = fail_times
        self._call_count = 0
        self._duration = duration_minutes
        self._difficulty = difficulty
        self._xp_reward = xp_reward
        self._reflection_text = reflection_text
        self._reflection_fail = reflection_fail

    @property
    def model_name(self) -> str:
        return "fake-model-test-only"

    async def generate_quest(self, request: QuestGenerationRequest) -> RawModelOutput:
        self._call_count += 1

        if self._call_count <= self._fail_times:
            return RawModelOutput(
                text="",
                model_name=self.model_name,
                prompt_version=QUEST_PROMPT_VERSION,
            )

        if self._response == "AUTO":
            # Use the request's difficulty and compute a valid XP reward
            difficulty = request.difficulty if request.difficulty else self._difficulty
            xp_map = {
                "chill": 75,
                "curious": 100,
                "explorer": 150,
                "chaos": 150,
            }
            xp = xp_map.get(difficulty, self._xp_reward)
            text = _valid_quest_json(
                duration_minutes=request.duration_minutes,
                difficulty=difficulty,
                xp_reward=xp,
            )
        elif self._response is None:
            text = ""
        else:
            text = self._response

        return RawModelOutput(
            text=text,
            model_name=self.model_name,
            prompt_version=QUEST_PROMPT_VERSION,
        )

    async def generate_reflection(self, request: ReflectionRequest) -> RawModelOutput:
        if self._reflection_fail:
            from app.ai.base import ProviderUnavailableError

            raise ProviderUnavailableError("Fake reflection provider unavailable")
        text = (
            self._reflection_text
            if self._reflection_text is not None
            else "Well done, brave adventurer. The quest is complete."
        )
        return RawModelOutput(
            text=text,
            model_name=self.model_name,
            prompt_version="reflection_v2",
        )

    @property
    def call_count(self) -> int:
        return self._call_count


from app.ai.base import EvidenceAnalysisRequest, EvidenceAnalysisResult, VisionModelProvider


class FakeVisionProvider(VisionModelProvider):
    def __init__(self, result: EvidenceAnalysisResult | None = None) -> None:
        self._result = result or EvidenceAnalysisResult(
            visible_content="A fake leaf.",
            is_relevant=True,
            confidence=0.9,
            safety_concerns=[],
            completion_recommendation=True,
            model_name="fake-vision",
            model_version="1.0",
        )

    @property
    def model_name(self) -> str:
        return "fake-vision-test-only"

    async def analyze_evidence(self, request: EvidenceAnalysisRequest) -> EvidenceAnalysisResult:
        return self._result
