class TestAIHealthEndpoint:
    async def test_health_unauthenticated_returns_401(self, async_client):
        resp = await async_client.get(f"{BASE_AI}/health")
        assert resp.status_code == 401, resp.text

    @respx.mock
    async def test_health_reachable_true_when_ollama_up(self, make_client_with_provider):
        """With a real OllamaTextProvider and mocked HTTP → reachable=True."""
        from app.ai.providers.ollama_provider import OllamaTextProvider

        respx.get(VERSION_URL).mock(return_value=Response(200, json={"version": "0.5.1"}))
        provider = OllamaTextProvider(base_url=OLLAMA_BASE, model="test-model", timeout=5.0)
        async with make_client_with_provider(provider) as client:
            reg = await client.post(
                f"{BASE_AUTH}/register",
                json=_reg("aihealth1", "aihealth1@example.com"),
            )
            t = reg.json()["token"]["access_token"]
            resp = await client.get(f"{BASE_AI}/health", headers=_auth(t))

        assert resp.status_code == 200, resp.text
        body = resp.json()
        assert body["reachable"] is True
        assert body["provider"] == "ollama"
        assert body["configured_model"] == "test-model"
        assert body["server_version"] == "0.5.1"
        assert body["error"] is None
        assert body["latency_ms"] is not None and body["latency_ms"] >= 0

    @respx.mock
    async def test_health_reachable_false_when_ollama_down(self, make_client_with_provider):
        """Ollama unreachable → reachable=False, still returns HTTP 200."""
        from app.ai.providers.ollama_provider import OllamaTextProvider

        respx.get(VERSION_URL).mock(side_effect=ConnectError("refused"))
        provider = OllamaTextProvider(base_url=OLLAMA_BASE, model="test-model", timeout=5.0)
        async with make_client_with_provider(provider) as client:
            reg = await client.post(
                f"{BASE_AUTH}/register",
                json=_reg("aihealth2", "aihealth2@example.com"),
            )
            t = reg.json()["token"]["access_token"]
            resp = await client.get(f"{BASE_AI}/health", headers=_auth(t))

        # Must still be 200 — application must not crash when Ollama is offline
        assert resp.status_code == 200, resp.text
        body = resp.json()
        assert body["reachable"] is False
        assert body["error"] is not None
        assert body["latency_ms"] is None

