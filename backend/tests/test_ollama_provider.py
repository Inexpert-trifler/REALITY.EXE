"""Integration tests for the Ollama provider and AI health endpoint.

Uses respx to intercept httpx calls, giving us a fully deterministic
mocked Ollama HTTP server — no real Ollama instance required.

Covers:
  OllamaTextProvider unit behaviour (mocked HTTP):
    - successful generate_quest returns RawModelOutput
    - structured JSON format parameter is sent
    - model name and prompt_version are set correctly
    - prompt_tokens and completion_tokens captured from response
    - temperature, max_tokens sent in options
    - connection error raises ProviderUnavailableError
    - timeout raises ProviderUnavailableError
    - HTTP 500 retries then raises ProviderUnavailableError
    - HTTP 503 retries (configurable max_retries)
    - HTTP 400 is NOT retried (client error, permanent)
    - empty response body raises ProviderUnavailableError
    - empty 'response' field raises ProviderOutputError
    - generate_reflection does NOT send JSON format param
    - reflection temperature is lower than quest temperature

  check_health():
    - reachable=True when /api/version returns 200
    - server_version extracted from response
    - latency_ms is a non-negative float
    - reachable=False when connection refused
    - reachable=False when timeout
    - never raises — always returns OllamaHealthResult

  GET /api/v1/ai/health endpoint:
    - 401 when unauthenticated
    - 200 with reachable=True when Ollama is up
    - 200 with reachable=False when Ollama is down (never 5xx)
    - response contains all required fields
    - configured_model matches settings
"""

import json

import pytest
import respx
from httpx import ConnectError, Request, Response, TimeoutException

from app.ai.base import (
    ProviderOutputError,
    ProviderUnavailableError,
    QuestGenerationRequest,
    ReflectionRequest,
)
from app.ai.providers.ollama_provider import OllamaTextProvider

BASE_AUTH = "/api/v1/auth"
BASE_AI = "/api/v1/ai"

# ---------------------------------------------------------------------------
# Shared fixtures / helpers
# ---------------------------------------------------------------------------

OLLAMA_BASE = "http://localhost:11434"
GENERATE_URL = f"{OLLAMA_BASE}/api/generate"
VERSION_URL = f"{OLLAMA_BASE}/api/version"


def _make_provider(max_retries: int = 2, **kwargs) -> OllamaTextProvider:
    """Create a provider pointing at the mock base URL."""
    return OllamaTextProvider(
        base_url=OLLAMA_BASE,
        model="test-model",
        timeout=5.0,
        temperature=0.85,
        max_tokens=512,
        max_retries=max_retries,
        **kwargs,
    )


def _valid_generate_response(model: str = "test-model", response_text: str = "{}") -> dict:
    """Build a realistic /api/generate response payload."""
    return {
        "model": model,
        "created_at": "2024-01-01T00:00:00Z",
        "response": response_text,
        "done": True,
        "total_duration": 5000000000,
        "load_duration": 1000000,
        "prompt_eval_count": 42,
        "eval_count": 128,
        "eval_duration": 2000000000,
    }


def _valid_quest_json() -> str:
    return json.dumps(
        {
            "title": "The Mocked Quest",
            "brief": "A quest generated by the mocked Ollama server for testing.",
            "duration_minutes": 20,
            "difficulty": "chill",
            "objectives": [
                {"id": "obj-1", "instruction": "Find a leaf", "optional": False},
            ],
            "xp_reward": 75,
            "evidence_required": True,
            "safety_notes": "Stay on public paths.",
        }
    )


def _reg(username: str, email: str) -> dict:
    return {
        "username": username,
        "email": email,
        "password": "Secure1234",
        "display_name": f"Player {username}",
    }


def _auth(token: str) -> dict:
    return {"Authorization": f"Bearer {token}"}


