class TestOllamaGenerateReflection:
    @respx.mock
    async def test_reflection_returns_plain_text(self):
        reflection_text = "Well done, brave adventurer!"
        respx.post(GENERATE_URL).mock(
            return_value=Response(200, json=_valid_generate_response(response_text=reflection_text))
        )
        provider = _make_provider()
        req = ReflectionRequest(
            quest_title="The Park Walk",
            quest_brief="Walk to the park.",
            outcome="success",
            earned_xp=100,
            personality="Wizard",
        )
        result = await provider.generate_reflection(req)
        assert result.text == reflection_text
        assert result.prompt_version == "reflection_v2"

    @respx.mock
    async def test_reflection_does_not_send_json_format(self):
        """Reflections are plain text — `format` key must NOT be sent."""
        captured: list[dict] = []

        async def _capture(request: Request) -> Response:
            captured.append(json.loads(request.content))
            return Response(200, json=_valid_generate_response(response_text="Great job!"))

        respx.post(GENERATE_URL).mock(side_effect=_capture)
        provider = _make_provider()
        req = ReflectionRequest(
            quest_title="Test",
            quest_brief="Brief.",
            outcome="success",
            earned_xp=50,
            personality="Sensei",
        )
        await provider.generate_reflection(req)
        assert captured
        # format must be absent (reflections are free text)
        assert "format" not in captured[0], (
            "generate_reflection must not send `format` — reflections are plain text"
        )

    @respx.mock
    async def test_reflection_uses_lower_temperature(self):
        """Reflections should use temperature < quest generation temperature."""
        captured_quest: list[dict] = []
        captured_refl: list[dict] = []
        call_num = 0

        async def _capture(request: Request) -> Response:
            nonlocal call_num
            data = json.loads(request.content)
            if call_num == 0:
                captured_quest.append(data)
            else:
                captured_refl.append(data)
            call_num += 1
            return Response(200, json=_valid_generate_response(response_text=_valid_quest_json()))

        respx.post(GENERATE_URL).mock(side_effect=_capture)
        provider = _make_provider()

        # Quest call
        await provider.generate_quest(
            QuestGenerationRequest(
                duration_minutes=20,
                environment="park",
                difficulty="chill",
                play_style="explorer",
                personality="Wizard",
            )
        )
        # Reflection call
        respx.post(GENERATE_URL).mock(side_effect=_capture)
        await provider.generate_reflection(
            ReflectionRequest(
                quest_title="T",
                quest_brief="B",
                outcome="success",
                earned_xp=0,
                personality="Wizard",
            )
        )

        if captured_quest and captured_refl:
            quest_temp = captured_quest[0]["options"]["temperature"]
            refl_temp = captured_refl[0]["options"]["temperature"]
            assert refl_temp < quest_temp, (
                f"Reflection temp ({refl_temp}) should be lower than quest temp ({quest_temp})"
            )


